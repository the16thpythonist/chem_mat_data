def _download_zenodo_csv(e: Experiment) -> str:
    """
    Download the Epoxy CSV from Zenodo, caching in the experiment folder.

    Uses ``curl`` as a subprocess because the Zenodo file server sometimes
    stalls with Python ``requests`` in certain network environments.

    :param e: The running experiment instance.
    :returns: Absolute path to the downloaded CSV.
    """
    csv_path = os.path.join(e.path, ZENODO_FILENAME)
    if os.path.exists(csv_path) and os.path.getsize(csv_path) > 1_000_000:
        e.log(f'Using cached {ZENODO_FILENAME} ({os.path.getsize(csv_path) / 1e6:.1f} MB)')
        return csv_path

    e.log(f'Downloading {ZENODO_FILENAME} from Zenodo (~265 MB)...')
    result = subprocess.run(
        ['curl', '-sL', '-o', csv_path, ZENODO_URL],
        timeout=600,
        capture_output=True,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f'curl failed with code {result.returncode}: {result.stderr.decode()}'
        )

    size_mb = os.path.getsize(csv_path) / 1e6
    e.log(f'Downloaded {size_mb:.1f} MB')
    return csv_path


def _sanitize_polymer_smiles(smiles: str) -> str:
    """
    Replace ``*`` attachment-point wildcards with ``[H]`` so RDKit can parse
    the polymer SMILES as a valid molecule fragment.
    """
    return smiles.replace('*', '[H]')


@experiment.hook('load_dataset', default=False, replace=True)
def load_dataset(e: Experiment) -> Dict[int, dict]:
    """
    Download and process the PolyUniverse Epoxy dataset.

    Downloads the ~265 MB CSV from Zenodo, sanitises polymer SMILES for RDKit,
    and returns a dictionary of polymers with 13 predicted properties as
    regression targets.

    :returns: Dictionary mapping indices to polymer data dictionaries.
    """
    csv_path = _download_zenodo_csv(e)
    df = pd.read_csv(csv_path)
    e.log(f'Loaded CSV with {len(df)} rows, columns: {list(df.columns)}')

    dataset: Dict[int, dict] = {}
    index = 0
    invalid = 0

    for _, row in df.iterrows():
        raw_smiles = str(row['Smiles']).strip()
        if not raw_smiles or raw_smiles == 'nan':
            continue

        smiles = _sanitize_polymer_smiles(raw_smiles)
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            invalid += 1
            continue

        targets = [float(row[col]) for col in TARGET_COLUMNS]

        dataset[index] = {
            'smiles': smiles,
            'targets': targets,
            'raw_smiles': raw_smiles,
            'monomer_1': str(row.get('Smiles_Compound_1', '')),
            'monomer_2': str(row.get('Smiles_Compound_2', '')),
        }
        index += 1

    e.log(f'Processed {len(dataset)} polymers ({invalid} invalid SMILES skipped)')
    return dataset


@experiment.hook('add_graph_metadata', default=False, replace=True)
def add_graph_metadata(_e: Experiment, data: dict, graph: dict) -> None:
    """Add polymer-specific metadata to each graph."""
    graph['graph_raw_smiles'] = data['raw_smiles']
    graph['graph_monomer_1'] = data['monomer_1']
    graph['graph_monomer_2'] = data['monomer_2']


experiment.run_if_main()
