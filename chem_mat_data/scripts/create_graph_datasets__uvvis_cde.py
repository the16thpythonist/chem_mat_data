"""
Processing of the auto-generated UV/vis absorption database of Beard et al. (Sci. Data 2019) into the graph format.

The database was text-mined from about 400,000 articles with ChemDataExtractor and contains experimental UV/vis
absorption maxima (and, where reported, extinction coefficients) of about 8,500 compounds. For a subset, the
authors also computed the first excitation wavelength and oscillator strength with the simplified Tamm-Dancoff
approach (sTDA) and with TD-DFT. Values that are not available are NaN.

The CSV file inside the archive has a header line whose column names contain unquoted commas; it is therefore read
with explicit column names (8 columns: SMILES, sTDA wavelength, sTDA oscillator strength, TD-DFT wavelength,
TD-DFT oscillator strength, experimental wavelength, experimental extinction coefficient, solvent).
"""
