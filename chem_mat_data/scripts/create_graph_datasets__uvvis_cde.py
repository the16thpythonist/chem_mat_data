__TESTING__ = False

experiment = Experiment.extend(
    'create_graph_datasets.py',
    base_path=folder_path(__file__),
    namespace=file_namespace(__file__),
    glob=globals(),
)


def to_float(value: str) -> float:
    """
    Converts a CSV cell to float, returning NaN for empty, "NaN" or non-numeric cells.

    :param value: The raw cell content.

    :returns: The float value or NaN.
    """
    try:
        x = float(value)
    except (TypeError, ValueError):
        return float('nan')
    return x if math.isfinite(x) else float('nan')


@experiment.hook('add_graph_metadata', default=False, replace=True)
def add_graph_metadata(e: Experiment, data: dict, graph: dict) -> dict:
    """
    Stores the row index of the source CSV as graph id and the extracted solvent string.
    """
    graph['graph_id'] = data['row']
    graph['graph_solvent'] = data['solvent']


@experiment.hook('load_dataset', default=False, replace=True)
def load_dataset(e: Experiment) -> Dict[int, dict]:
    """
    Downloads data.zip from Figshare, extracts the CSV and converts every valid row into a dataset element.

    :returns: A dict mapping integer indices to dicts with the keys 'smiles', 'targets', 'solvent' and 'row'.
    """
    with FigshareSource(file_id=e.FIGSHARE_FILE_ID, relative_path=e.CSV_PATH, verbose=True) as source:
        path = source.fetch()
        with open(path, newline='') as file:
            reader = csv.reader(file)
            next(reader)  # unparseable header line
            rows = [r for r in reader if len(r) == len(e.RAW_COLUMNS)]
    e.log(f'read {len(rows)} rows')

    order = ['lambda_exp', 'eps_exp', 'lambda_stda', 'f_stda', 'lambda_tddft', 'f_tddft']
    dataset: Dict[int, dict] = {}
    index = 0
    for row_index, values in enumerate(rows):
        row = dict(zip(e.RAW_COLUMNS, values))
        smiles = row['smiles'].strip()
        if not smiles or '.' in smiles:
            continue
        mol = Chem.MolFromSmiles(smiles)
        if mol is None or mol.GetNumAtoms() < 2:
            continue
        targets = [to_float(row[key]) for key in order]
        if all(math.isnan(t) for t in targets):
            continue
        solvent = row['solvent'].strip()
        dataset[index] = {
            'smiles': smiles,
            'targets': targets,
            'solvent': '' if solvent in ('NaN', 'nan') else solvent,
            'row': row_index,
        }
        index += 1

    return dataset


experiment.run_if_main()
